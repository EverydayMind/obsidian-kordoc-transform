import { readFile, writeFile } from "node:fs/promises";
import { BUILTIN_TEMPLATES } from "kordoc";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const templates = await Promise.all(BUILTIN_TEMPLATES.map(async (t) => ({
  ...t,
  base64: (await readFile(`${root}node_modules/kordoc/templates/${t.file}`)).toString("base64"),
  sample: JSON.parse(await readFile(`${root}node_modules/kordoc/templates/${t.sampleFile}`, "utf8")),
})));
const output = `${root}src/template-data.ts`;
const content = `// Generated by scripts/embed-assets.mjs; kordoc MIT/rhwp forms MIT.\nexport const EMBEDDED_TEMPLATES = ${JSON.stringify(templates)} as const;\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('src/template-data.ts is stale; run npm run prepare:lazy');
} else await writeFile(output, content);
console.log(`Embedded ${templates.length} templates.`);
