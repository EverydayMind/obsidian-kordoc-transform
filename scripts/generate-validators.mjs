import { mkdir, readFile, writeFile } from 'node:fs/promises';
import Ajv from 'ajv8';
import standaloneCode from 'ajv8/dist/standalone/index.js';

const schemas = [
  ['snapshot', 'contracts/report-style/v1/snapshot.schema.json'],
  ['semantic-evidence', 'contracts/report-style/v2/semantic-evidence.schema.json'],
];
for (const [name, input] of schemas) {
  const schema = JSON.parse(await readFile(input, 'utf8'));
  const ajv = new Ajv({ strict: false, strictNumbers: true, coerceTypes: false, useDefaults: false, removeAdditional: false, code: { source: true, esm: true } });
  let code = standaloneCode(ajv, ajv.compile(schema));
  code = code.replace(/^"use strict";\s*/, '');
  code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
  if (/\brequire\s*\(/.test(code)) throw new Error(`${name}: unexpected runtime require`);
  code = `function ucs2length(value) { return [...value].length; }\n${code}`;
  const output = `// Generated by scripts/generate-validators.mjs. Do not edit.\n/* eslint-disable no-redeclare, no-unreachable -- Ajv emits function-scoped variables and unreachable branches in standalone validators. */\n${code}\n/* eslint-enable no-redeclare, no-unreachable -- End of generated validator. */\n`;
  const target = `src/style-profile/generated/${name}.js`;
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8').catch(() => '') !== output) throw new Error(`${target} is stale`);
  } else {
    await mkdir('src/style-profile/generated', { recursive: true });
    await writeFile(target, output);
  }
  console.log(`${target}: ${process.argv.includes('--check') ? 'verified' : 'generated'}`);
}
